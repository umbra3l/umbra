#!/usr/bin/env python3
"""Bakes the TUI's display words (tool names) from URW Gothic Demi into
anti-aliased coverage bitmaps, so the TUI can draw large type in half-block
"pixels" on any machine without the font installed.

  python3 -I tools/bake-type.py > src/typebake.ts

One bitmap per word per pixel height. A half-block pixel is one cell wide and
half a cell tall, about 1.1x taller than wide in kitty (PIXEL_ASPECT). Heights are
font-metric heights (ascent + descent), identical for every word at a size,
so names share a baseline. Requires ImageMagick only at bake time.

  python3 -I tools/bake-type.py --word umbra --height 14   # one bitmap as JSON
                                                         # (tools/banner.ts)
"""
import base64, subprocess, sys

FONT = "/usr/share/fonts/gsfonts/URWGothic-Demi.otf"
WORDS = ["claude", "opencode", "agy"]
HEIGHTS = [8, 10, 12, 14, 16, 18, 20, 24]  # in half-block pixels (2 per row)
SS = 8  # supersampling factor: exact-ish area coverage per pixel
# A half-block pixel is one cell wide and half a cell tall. Terminal cells are
# ~1:2.2 (JetBrains Mono in kitty), so the pixel is 1.1x taller than wide;
# baking as if it were square stretched every name ~10% too wide.
PIXEL_ASPECT = 1.1

def render(word, h):
    # Render large, then area-average down: crisp coverage values.
    big = subprocess.run(
        ["magick", "-background", "black", "-fill", "white", "-font", FONT,
         "-pointsize", str(h * SS * 1.18), f"label:{word}", "-depth", "8",
         "-format", "%w %h", "info:"], capture_output=True, text=True, check=True).stdout.split()
    bw, bh = int(big[0]), int(big[1])
    w = max(1, round(bw / SS * PIXEL_ASPECT))
    raw = subprocess.run(
        ["magick", "-background", "black", "-fill", "white", "-font", FONT,
         "-pointsize", str(h * SS * 1.18), f"label:{word}",
         "-filter", "box", "-resize", f"{w}x{h}!", "-colorspace", "gray", "-depth", "8", "gray:-"],
        capture_output=True, check=True).stdout
    return w, h, raw

if len(sys.argv) == 5 and sys.argv[1] == "--word" and sys.argv[3] == "--height":
    import json
    w, h, raw = render(sys.argv[2], int(sys.argv[4]))
    rows = [r for r in range(h) if max(raw[r*w:(r+1)*w]) > 8]
    cols = [c for c in range(w) if any(raw[r*w + c] > 8 for r in rows)]
    r0, r1, c0, c1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    if (r1 - r0) % 2: r1 = r1 + 1 if r1 < h else r1; r0 = r0 - 1 if (r1 - r0) % 2 else r0
    data = bytes(raw[r*w + c] for r in range(r0, r1) for c in range(c0, c1))
    print(json.dumps({"w": c1 - c0, "h": r1 - r0, "data": base64.b64encode(data).decode()}))
    sys.exit(0)

out = {}
for h in HEIGHTS:
    rendered = {wd: render(wd, h) for wd in WORDS}
    # Drop rows that are blank in every word at this size (shared padding).
    rows = [r for r in range(h) if any(max(raw[r*w:(r+1)*w]) > 8 for w, _, raw in rendered.values())]
    r0, r1 = rows[0], rows[-1] + 1
    if (r1 - r0) % 2:  # keep an even pixel height (whole cells)
        r1 = min(h, r1 + 1) if r1 < h else r1
        if (r1 - r0) % 2: r0 = max(0, r0 - 1)
    for wd, (w, _, raw) in rendered.items():
        cols = [c for c in range(w) if any(raw[r*w + c] > 8 for r in range(r0, r1))]
        c0, c1 = cols[0], cols[-1] + 1
        data = bytes(raw[r*w + c] for r in range(r0, r1) for c in range(c0, c1))
        out.setdefault(wd, []).append((c1 - c0, r1 - r0, base64.b64encode(data).decode()))

print("// Generated by tools/bake-type.py from URW Gothic Demi (URW base35, AGPL with font exception).")
print("// Coverage bitmaps (0-255) per word and size; width/height in half-block pixels.")
print("export interface Bitmap { w: number; h: number; data: string }")
print("export const TYPE: Record<string, Bitmap[]> = {")
for wd, sizes in out.items():
    print(f"  {wd}: [")
    for w, h, d in sizes:
        print(f'    {{ w: {w}, h: {h}, data: "{d}" }},')
    print("  ],")
print("}")
